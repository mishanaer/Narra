async function downloadWsExport(page) {
  const url = `${WSEXPORT}?lang=ru&format=epub-3&page=${encodeURIComponent(page.replace(/ /g, "_"))}`;
  let lastErr;
  for (let attempt = 0; attempt <= 2; attempt++) {
    try {
      const res = await politeFetch(url, { pause: WS_PAUSE_MS, timeout: WS_TIMEOUT_MS, kind: "ws" });
      if (res.status === 429 || res.status >= 500) {
        lastErr = new Error(`HTTP ${res.status}`);
        log(`  WSExport ${res.status}, пауза 30 с…`);
        await sleep(30000);
        continue;
      }
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.length < 4 || buf[0] !== 0x50 || buf[1] !== 0x4b) throw new Error("not-a-zip");
      return buf;
    } catch (e) {
      lastErr = e;
      if (attempt < 2) {
        log(`  retry ${attempt + 1}/2: ${e.message}`);
        await sleep(e.message === "not-a-zip" ? 5000 : 30000);
      }
    }
  }
  throw new Error(`wsexport: ${lastErr.message}`);
}

// ---------------------------------------------------------------------------
// Валидация EPUB (минимальный zip-ридер, как в fetch-en-catalog)
// ---------------------------------------------------------------------------
function readZipEntries(buf) {
  const maxScan = Math.min(buf.length, 65557);
  let eocd = -1;
  for (let i = buf.length - 22; i >= buf.length - maxScan; i--) {
    if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
  }
  if (eocd < 0) throw new Error("zip: EOCD not found");
  const count = buf.readUInt16LE(eocd + 10);
  const cdOffset = buf.readUInt32LE(eocd + 16);
  const entries = new Map();
  let p = cdOffset;
  for (let i = 0; i < count; i++) {
    if (p + 46 > buf.length || buf.readUInt32LE(p) !== 0x02014b50) throw new Error("zip: bad central directory");
    const method = buf.readUInt16LE(p + 10);
    const compSize = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const localOff = buf.readUInt32LE(p + 42);
    const name = buf.toString("utf8", p + 46, p + 46 + nameLen);
    entries.set(name, { method, compSize, localOff });
    p += 46 + nameLen + extraLen + commentLen;
  }
  return entries;
}

function zipEntryData(buf, entry) {
  const p = entry.localOff;
  if (buf.readUInt32LE(p) !== 0x04034b50) throw new Error("zip: bad local header");
  const nameLen = buf.readUInt16LE(p + 26);
  const extraLen = buf.readUInt16LE(p + 28);
  const start = p + 30 + nameLen + extraLen;
  const comp = buf.subarray(start, start + entry.compSize);
  if (entry.method === 0) return Buffer.from(comp);
  if (entry.method === 8) return zlib.inflateRawSync(comp);
  throw new Error(`zip: unsupported method ${entry.method}`);
}

function attrOf(tag, name) {
  const m = tag.match(new RegExp(`${name}\\s*=\\s*"([^"]*)"`, "i")) || tag.match(new RegExp(`${name}\\s*=\\s*'([^']*)'`, "i"));
  return m ? m[1] : null;
}

function stripXml(xhtml) {
  return xhtml
    .replace(/<head[\s\S]*?<\/head>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ");
}

function validateEpub(buf, kind) {
  let entries;
  try {
    entries = readZipEntries(buf);
  } catch (e) {
    return { ok: false, reason: `zip-broken: ${e.message}` };
  }
  try {
    const mt = entries.get("mimetype");
    if (!mt) return { ok: false, reason: "mimetype-missing" };
    if (zipEntryData(buf, mt).toString("utf8").trim() !== "application/epub+zip") {
      return { ok: false, reason: "mimetype-bad" };
    }
    const containerEntry = entries.get("META-INF/container.xml");
    if (!containerEntry) return { ok: false, reason: "container-missing" };
    const container = zipEntryData(buf, containerEntry).toString("utf8");
    const opfPath = attrOf(container.match(/<rootfile\b[^>]*>/i)?.[0] || "", "full-path");
    if (!opfPath || !entries.get(opfPath)) return { ok: false, reason: "opf-missing" };
    const opf = zipEntryData(buf, entries.get(opfPath)).toString("utf8");
    const opfDir = opfPath.includes("/") ? opfPath.slice(0, opfPath.lastIndexOf("/") + 1) : "";

    const languages = [...opf.matchAll(/<dc:language[^>]*>([\s\S]*?)<\/dc:language>/gi)].map((m) => m[1].trim());
    if (!languages.some((l) => /^ru/i.test(l))) return { ok: false, reason: `language-bad: ${languages.join(",") || "none"}` };

    const items = new Map();
    for (const m of opf.matchAll(/<(?:opf:)?item\b[^>]*>/gi)) {
      const id = attrOf(m[0], "id");
      if (id) items.set(id, { href: attrOf(m[0], "href"), type: attrOf(m[0], "media-type") || "" });
    }
    const spineIds = [...opf.matchAll(/<(?:opf:)?itemref\b[^>]*>/gi)].map((m) => attrOf(m[0], "idref")).filter(Boolean);
    if (new Set(spineIds).size < 2) return { ok: false, reason: `spine-too-short: ${spineIds.length}` };

    let textBytes = 0;
    let anchorCount = 0;
    for (const id of spineIds) {
      const item = items.get(id);
      if (!item || !item.href || !/xhtml|html/i.test(item.type)) continue;
      if (id === "title" || id === "about" || id === "nav" || id === "cover") continue;
      const href = decodeURIComponent(item.href.split("#")[0]);
      const full = path.posix.normalize(opfDir + href);
      const entry = entries.get(full) || entries.get(href);
      if (!entry) continue;
      try {
        const xhtml = zipEntryData(buf, entry).toString("utf8");
        textBytes += Buffer.byteLength(stripXml(xhtml).trim());
        anchorCount += (xhtml.match(/rel="mw:WikiLink"/g) || []).length;
      } catch { /* учтено порогом */ }
    }
    const minText = KIND_MIN[kind] ?? KIND_MIN.povest;
    if (textBytes < minText) return { ok: false, reason: `text-too-small: ${textBytes} < ${minText}` };
    // дизамбиг-страница: мало текста и куча ссылок
    if (textBytes < 20 * 1024 && anchorCount > 30) return { ok: false, reason: "looks-like-disambig" };

    return { ok: true, spineCount: new Set(spineIds).size, textBytes };
  } catch (e) {
    return { ok: false, reason: `epub-parse: ${e.message}` };
  }
}

