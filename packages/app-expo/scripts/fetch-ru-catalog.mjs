function displayTitle(entry) {
  return (entry.dt || entry.t).replace(/\s*\([^()]*\)\s*$/, "") || entry.t;
}

async function acquire(state, ctx, entry, source) {
  const author = AUTHORS[entry.s].an;
  const title = displayTitle(entry);
  const dupKey = `${normRu(title)}::${normRu(author)}`;
  if (ctx.dupKeys.has(dupKey)) return { skipped: "dup" };

  let resolved;
  try {
    resolved = await resolveEntry(entry);
  } catch (e) {
    state.misses.push({ title, author, reason: `resolve-error: ${e.message}` });
    saveState(state);
    return { skipped: "resolve-error" };
  }
  if (resolved.miss) {
    state.misses.push({ title, author, reason: resolved.miss });
    saveState(state);
    log(`  MISS: ${title} (${author}) — ${resolved.miss}`);
    return { skipped: "miss" };
  }
  const page = resolved.page;
  if (ctx.pages.has(page)) return { skipped: "dup-page" };
  if (state.rejected.some((rj) => rj.page === page)) return { skipped: "rejected-earlier" };

  // Правовая проверка переводчика (для переводов)
  if (entry.foreign) {
    const verdict = await vetTranslatorByPage(page, resolved.translator);
    if (!verdict.ok) {
      state.rejected.push({ page, title, author, reason: verdict.reason });
      saveState(state);
      log(`  REJECT: ${verdict.reason}`);
      return { skipped: "translator" };
    }
    resolved.translator = {
      surname: resolved.translator?.surname || verdict.display,
      died: verdict.died,
      display: verdict.display || resolved.translator?.display,
    };
  }

  if (PHASE === "resolve") {
    ctx.pages.add(page);
    ctx.dupKeys.add(dupKey);
    log(`  RESOLVED: ${page}${resolved.translator ? ` [пер. ${resolved.translator.display}]` : ""}`);
    ctx.resolved.push({ title, author, page });
    return { resolved: true };
  }

  log(`  ⇣ ${page}`);
  let buf;
  try {
    buf = await downloadWsExport(page);
  } catch (e) {
    state.rejected.push({ page, title, author, reason: e.message });
    saveState(state);
    log(`  FAIL: ${e.message}`);
    return { skipped: "wsexport" };
  }
  const v = validateEpub(buf, entry.k);
  if (!v.ok) {
    state.rejected.push({ page, title, author, reason: v.reason });
    saveState(state);
    log(`  REJECT: ${v.reason}`);
    return { skipped: "invalid" };
  }

  let slug = slugify(title);
  if (ctx.slugs.has(slug)) slug = `${slug}-${slugify(entry.s).slice(0, 20)}`;
  if (ctx.slugs.has(slug)) slug = `${slug}-${state.done.length}`;
  ctx.slugs.add(slug);
  const file = `${slug}.epub`;
  const abs = path.join(OUT_DIR, file);
  fs.writeFileSync(abs, buf);

  const translatorDisplay = resolved.translator
    ? resolved.translator.display === resolved.translator.surname
      ? resolved.translator.surname
      : resolved.translator.display
    : entry.tr || null;
  const subtitle = entry.sub || (translatorDisplay ? `перевод: ${translatorDisplay}` : undefined);
  const cl = cleanEpubFile(abs, { title, author, subtitle });
  const finalBuf = fs.readFileSync(abs);
  const v2 = validateEpub(finalBuf, entry.k);
  if (!v2.ok) {
    // чистка что-то сломала — откатываемся на оригинал
    fs.writeFileSync(abs, buf);
  }
  const vFinal = v2.ok ? v2 : v;
  const bytes = fs.statSync(abs).size;

  const rec = {
    slug,
    title,
    author,
    translator: translatorDisplay || undefined,
    genre: entry.g,
    kind: entry.k,
    wikisourcePage: page,
    file,
    bytes,
    sha256: crypto.createHash("sha256").update(fs.readFileSync(abs)).digest("hex"),
    textBytes: vFinal.textBytes,
    spineCount: vFinal.spineCount,
    source,
    cleaned: cl.cleaned,
    ...(cl.note ? { cleanNote: cl.note } : {}),
  };
  state.done.push(rec);
  ctx.pages.add(page);
  ctx.dupKeys.add(dupKey);
  saveState(state);
  log(`  ✓ [${state.done.length}/${TOTAL_TARGET}] ${title} — ${author} (${Math.round(vFinal.textBytes / 1024)} КБ текста)`);
  return { done: true };
}

