const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);
const sleep = (ms) => new Promise((res) => setTimeout(res, ms));

function normRu(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/gi, " ")
    .trim();
}

const TRANSLIT = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i",
  й: "j", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t",
  у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "",
  э: "e", ю: "yu", я: "ya",
};
function slugify(s) {
  const lat = String(s || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .split("")
    .map((ch) => (TRANSLIT[ch] !== undefined ? TRANSLIT[ch] : ch))
    .join("");
  return (
    lat.replace(/[^a-z0-9]+/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "").slice(0, 70).replace(/-$/, "") || "kniga"
  );
}

let lastApiAt = 0;
let lastWsAt = 0;
async function politeFetch(url, { pause, timeout, kind, body }) {
  const last = kind === "ws" ? lastWsAt : lastApiAt;
  const wait = last + pause - Date.now();
  if (wait > 0) await sleep(wait);
  if (kind === "ws") lastWsAt = Date.now();
  else lastApiAt = Date.now();
  const ctrl = new AbortController();
  const to = setTimeout(() => ctrl.abort(), timeout);
  try {
    return await fetch(url, {
      headers: { "User-Agent": UA, ...(body ? { "Content-Type": "application/x-www-form-urlencoded" } : {}) },
      method: body ? "POST" : "GET",
      body,
      redirect: "follow",
      signal: ctrl.signal,
    });
  } finally {
    clearTimeout(to);
  }
}

async function apiJSON(params) {
  // POST: длинные списки titles в GET дают HTTP 414 (URI too long)
  const body = new URLSearchParams({ format: "json", ...params }).toString();
  for (let attempt = 0; ; attempt++) {
    try {
      const res = await politeFetch(API, { pause: API_PAUSE_MS, timeout: 60000, kind: "api", body });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (e) {
      if (attempt >= 3) throw new Error(`API ${params.action}/${params.list || params.prop || ""}: ${e.message}`);
      await sleep(3000 * (attempt + 1));
    }
  }
}

