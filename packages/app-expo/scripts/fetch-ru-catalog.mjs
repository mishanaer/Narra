/** Информация о страницах (батч ≤50): title → {title, length, disambig, missing} */
async function pageInfoBatch(titles) {
  const out = new Map();
  for (let i = 0; i < titles.length; i += 25) {
    const chunk = titles.slice(i, i + 25);
    let data;
    try {
      data = await apiJSON({
        action: "query",
        titles: chunk.join("|"),
        redirects: "1",
        prop: "info|pageprops",
      });
    } catch (e) {
      // битый батч не роняет весь прогон: страницы считаем неизвестными
      log(`  pageInfoBatch: пропускаю батч из ${chunk.length} (${e.message})`);
      for (const t of chunk) out.set(t, { title: t, missing: true, length: 0, disambig: false });
      continue;
    }
    const redirects = new Map((data.query?.redirects || []).map((r) => [r.from, r.to]));
    const normalized = new Map((data.query?.normalized || []).map((n) => [n.from, n.to]));
    const byTitle = new Map();
    for (const p of Object.values(data.query?.pages || {})) {
      byTitle.set(p.title, {
        title: p.title,
        length: p.length || 0,
        missing: "missing" in p,
        disambig: !!p.pageprops?.disambiguation,
      });
    }
    for (const t of chunk) {
      let key = normalized.get(t) || t;
      key = redirects.get(key) || key;
      out.set(t, byTitle.get(key) || { title: key, missing: true, length: 0, disambig: false });
    }
  }
  return out;
}

function parenOf(title) {
  const m = title.match(/\(([^()]*)\)\s*$/);
  return m ? m[1] : null;
}

/** Разбор части «Автор; Переводчик» из скобок заголовка. */
function parseTranslator(parenContent) {
  const parts = parenContent.split(";").map((x) => x.trim());
  if (parts.length < 2) return null;
  const trPart = parts[parts.length - 1].replace(/\/.*$/, "").trim();
  const surname = trPart.split(/\s+/).pop();
  // статический белый список
  for (const key of Object.keys(TRANSLATORS)) {
    if (normRu(key) === normRu(surname) || normRu(key) === normRu(trPart)) {
      return { surname: key, died: TRANSLATORS[key], display: trPart, whitelisted: true };
    }
  }
  // анонимный дореволюционный перевод, подписанный инициалами («Е. К.»)
  if (/^([А-ЯЁ]\.[\s-]*){1,3}$/.test(trPart)) {
    return { surname: trPart, died: null, display: trPart, anonymous: true };
  }
  return { surname, died: null, display: trPart, pending: true };
}

function translatorOk(parenContent) {
  const tr = parseTranslator(parenContent);
  return tr && (tr.whitelisted || tr.anonymous) ? tr : null;
}

// --- динамическая проверка переводчика по странице произведения -----------
const authorDeathCache = new Map(); // Автор:Имя → год смерти | null
const translatorVetCache = new Map(); // страница произведения → verdict

async function authorPageDeathYear(authorPageTitle) {
  if (authorDeathCache.has(authorPageTitle)) return authorDeathCache.get(authorPageTitle);
  let year = null;
  try {
    const data = await apiJSON({
      action: "query",
      titles: authorPageTitle,
      prop: "categories",
      cllimit: "100",
      redirects: "1",
    });
    for (const p of Object.values(data.query?.pages || {})) {
      for (const c of p.categories || []) {
        const m = c.title.match(/Умершие в (\d{3,4}) году/);
        if (m) year = +m[1];
      }
    }
  } catch { /* останется null */ }
  authorDeathCache.set(authorPageTitle, year);
  return year;
}

/**
 * Проверка переводчика для страницы-перевода: поле «ПЕРЕВОДЧИК» в вики-тексте
 * → страница Автор: → категория «Умершие в YYYY году» (нужно ≤ 1955).
 * Возвращает { ok, display?, died?, reason? }.
 */
async function vetTranslatorByPage(pageTitle, parsed) {
  if (parsed?.whitelisted || parsed?.anonymous) return { ok: true, display: parsed.display, died: parsed.died };
  if (translatorVetCache.has(pageTitle)) return translatorVetCache.get(pageTitle);
  let verdict = { ok: false, reason: "translator-unknown" };
  try {
    const data = await apiJSON({
      action: "query",
      titles: pageTitle,
      prop: "revisions",
      rvprop: "content",
      rvslots: "main",
      redirects: "1",
    });
    const page = Object.values(data.query?.pages || {})[0];
    const content = page?.revisions?.[0]?.slots?.main?.["*"] || "";
    const trLine = content.match(/ПЕРЕВОДЧИК\W{0,3}=([^\n]*)/)?.[1] || "";
    const authorLinks = [...trLine.matchAll(/\[\[Автор:([^\]|]+)/g)].map((m) => m[1].trim())
      .concat([...trLine.matchAll(/\{\{[Аа]втор\|([^}|]+)/g)].map((m) => m[1].trim()).map((n) => n));
    if (authorLinks.length) {
      const years = [];
      for (const a of authorLinks) {
        const y = await authorPageDeathYear(a.startsWith("Автор:") ? a : `Автор:${a}`);
        years.push({ a, y });
      }
      if (years.every((x) => x.y && x.y <= 1955)) {
        verdict = { ok: true, display: parsed?.display || years.map((x) => x.a).join(", "), died: Math.max(...years.map((x) => x.y)) };
      } else if (years.some((x) => x.y && x.y > 1955)) {
        verdict = { ok: false, reason: `translator-not-pd (умер ${years.find((x) => x.y > 1955).y})` };
      } else {
        verdict = { ok: false, reason: "translator-death-year-unknown" };
      }
    } else if (/неизвестен|анонимн/i.test(trLine)) {
      verdict = { ok: true, display: "неизвестный переводчик (дореволюционное издание)", died: null };
    } else if (parsed?.surname) {
      // запасной путь: поиск страницы Автор: по фамилии
      const sr = await apiJSON({
        action: "query",
        list: "search",
        srsearch: `intitle:${parsed.surname}`,
        srnamespace: "102",
        srlimit: "5",
      });
      const hits = (sr.query?.search || []).map((x) => x.title);
      const years = [];
      for (const h of hits) years.push(await authorPageDeathYear(h));
      const known = years.filter((y) => y);
      if (hits.length && known.length && years.every((y) => !y || y <= 1955) && known.length === hits.length) {
        verdict = { ok: true, display: parsed.display, died: Math.max(...known) };
      } else if (known.some((y) => y > 1955)) {
        verdict = { ok: false, reason: `translator-not-pd (умер ${known.find((y) => y > 1955)})` };
      } else {
        verdict = { ok: false, reason: "translator-death-year-unknown" };
      }
    }
  } catch (e) {
    verdict = { ok: false, reason: `translator-vet-error: ${e.message}` };
  }
  translatorVetCache.set(pageTitle, verdict);
  return verdict;
}

function titleMatchesWork(pageTitle, entry) {
  const base = pageTitle.replace(/\s*\([^()]*\)\s*$/, "");
  const want = entry.dt || entry.t.replace(/\s*\([^()]*\)\s*$/, "");
  const nb = normRu(base);
  const nw = normRu(want);
  // только точное совпадение базового названия — иначе ловим фрагменты
  // вида «Пошехонская старина. Начало» вместо целого произведения
  return nb === nw;
}

/** Резолв одной курируемой позиции → { page, translator? } или { miss } */
async function resolveEntry(entry) {
  const keys = authorKeys(entry.s);
  const candidates = [];
  if (entry.p) candidates.push(entry.p);
  if (!entry.foreign) {
    for (const k of keys) candidates.push(`${entry.t} (${k})`);
    candidates.push(entry.t);
  } else {
    if (entry.tr) for (const k of keys) candidates.push(`${entry.t} (${k}; ${entry.tr})`);
  }
  let translator = entry.tr ? { surname: entry.tr, died: TRANSLATORS[entry.tr], display: entry.tr } : null;

  if (candidates.length) {
    const info = await pageInfoBatch(candidates);
    for (const c of candidates) {
      const pi = info.get(c);
      if (pi && !pi.missing && !pi.disambig) {
        // для переводов: перепроверить переводчика по фактическому названию
        if (entry.foreign) {
          const paren = parenOf(pi.title);
          const trInfo = paren ? parseTranslator(paren) : null;
          if (trInfo) translator = trInfo;
        }
        return { page: pi.title, length: pi.length, translator };
      }
    }
  }

  // Поиск по названию
  const want = entry.dt || entry.t;
  const data = await apiJSON({
    action: "query",
    list: "search",
    srsearch: `intitle:"${want}"`,
    srnamespace: "0",
    srlimit: "50",
  });
  const results = (data.query?.search || [])
    .filter((rr) => !rr.title.includes("/"))
    .filter((rr) => !/\((ДО|ВТ|СО)\)\s*$/.test(rr.title))
    .filter((rr) => titleMatchesWork(rr.title, entry));

  const scored = [];
  for (const rr of results) {
    const paren = parenOf(rr.title);
    if (!paren) continue;
    if (!entry.foreign) {
      if (!keys.some((k) => normRu(paren) === normRu(k))) continue;
      scored.push({ title: rr.title, size: rr.size, translator: null });
    } else {
      const parts = paren.split(";").map((x) => x.trim());
      if (!keys.some((k) => normRu(parts[0]) === normRu(k))) continue;
      const trInfo = parseTranslator(paren);
      if (!trInfo) continue; // «(Автор)» без переводчика — редакционная страница
      let score = rr.size;
      if (trInfo.pending) score /= 4; // непроверенный переводчик — самый низкий приоритет
      else if (entry.tr && normRu(trInfo.surname) !== normRu(entry.tr)) score /= 2;
      scored.push({ title: rr.title, size: score, translator: trInfo });
    }
  }
  if (!scored.length) return { miss: entry.foreign ? "not-found-or-translator-not-pd" : "not-found" };
  scored.sort((a, b) => b.size - a.size);
  const best = scored[0];
  // финальная проверка: не дизамбиг
  const inf = (await pageInfoBatch([best.title])).get(best.title);
  if (!inf || inf.missing || inf.disambig) return { miss: "disambig-or-missing" };
  return { page: best.title, length: best.size, translator: best.translator || translator };
}

