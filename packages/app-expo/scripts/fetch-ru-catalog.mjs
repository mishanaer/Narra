function topupCandidateFromTitle(title, genre, kind) {
  if (title.includes("/")) return null;
  if (/^[«"„'…]/.test(title)) return null; // стихи по первой строке и цитатные заглавия
  if (/\((ДО|ВТ|СО|НЕТ)\)\s*$/.test(title)) return null;
  const paren = parenOf(title);
  if (!paren) return null;
  const parts = paren.split(";").map((x) => x.trim());
  const authorKeyRaw = parts[0];
  let authorKey = null;
  for (const [key, a] of Object.entries(AUTHORS)) {
    if ([key, ...(a.alt || [])].some((k) => normRu(k) === normRu(authorKeyRaw))) { authorKey = key; break; }
  }
  if (!authorKey) return null;
  const a = AUTHORS[authorKey];
  if (parts.length >= 2) {
    // перевод: переводчик должен хотя бы парситься (полная проверка — в acquire)
    const tr = parseTranslator(paren);
    if (!tr) return null;
  } else if (a.foreign) {
    return null; // зарубежный автор без переводчика в заголовке — редакционная страница
  }
  const base = title.replace(/\s*\([^()]*\)\s*$/, "");
  if (base.length < 3 || /^\d+$/.test(base)) return null;
  const genreFinal = a.shelf || (a.foreign ? "foreign-classics" : genre);
  return { t: base, dt: base, s: authorKey, g: genreFinal, k: kind, p: title, foreign: parts.length >= 2 };
}

async function topupPhase(state, ctx) {
  log("=== Добор из категорий Викитеки ===");
  const perAuthor = new Map();
  for (const d of state.done) perAuthor.set(d.author, (perAuthor.get(d.author) || 0) + 1);

  for (const [cat, genre, kind] of TOPUP_CATEGORIES) {
    if (state.done.length >= TOTAL_TARGET) break;
    log(`Категория: ${cat}`);
    let members;
    try {
      members = await listCategory(cat);
    } catch (e) {
      log(`  не удалось получить категорию: ${e.message}`);
      continue;
    }
    const candidates = members
      .map((t) => topupCandidateFromTitle(t, genre, kind))
      .filter(Boolean)
      .filter((c) => !ctx.pages.has(c.p))
      .filter((c) => !ctx.dupKeys.has(`${normRu(c.t)}::${normRu(AUTHORS[c.s].an)}`))
      .filter((c) => !state.rejected.some((rj) => rj.page === c.p));
    // размер страницы: батчами, крупные вперёд
    const infos = await pageInfoBatch(candidates.map((c) => c.p));
    for (const c of candidates) c.size = infos.get(c.p)?.length || 0;
    candidates.sort((x, y) => y.size - x.size);
    log(`  кандидатов после фильтров: ${candidates.length}`);
    for (const c of candidates) {
      if (state.done.length >= TOTAL_TARGET) break;
      const an = AUTHORS[c.s].an;
      if ((perAuthor.get(an) || 0) >= TOPUP_AUTHOR_CAP + (CURATED.some((e) => e.s === c.s) ? 20 : 0)) continue;
      const info = infos.get(c.p);
      if (info?.missing || info?.disambig) continue;
      try {
        const res = await acquire(state, ctx, c, "topup");
        if (res.done) perAuthor.set(an, (perAuthor.get(an) || 0) + 1);
      } catch (e) {
        log(`  ошибка на «${c.p}», пропускаю: ${e.message}`);
      }
    }
  }
}

