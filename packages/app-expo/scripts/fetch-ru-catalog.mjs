function cleanEpubFile(epubPath, meta) {
  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "ru-cat-clean-"));
  try {
    extractEpub(epubPath, workDir);
    if (!fs.existsSync(path.join(workDir, "OPS", "content.opf"))) {
      return { cleaned: false, note: "не WSExport-структура (OPS/content.opf нет) — оставлен как есть" };
    }
    const report = {};
    cleanWikisourceEpubDir(workDir, meta, report);
    packEpub(workDir, epubPath);
    return { cleaned: true, removed: (report.removed || []).length };
  } catch (e) {
    return { cleaned: false, note: `ошибка чистки: ${e.message}` };
  } finally {
    fs.rmSync(workDir, { recursive: true, force: true });
  }
}

