import type { NarraCharacter, NarraGender } from "./types";
import { type AssignVoicesOptions, assignVoices } from "./voice-rules";

type CharacterDefinition = {
  id: string;
  name: string;
  fullName: string;
  role: string;
  gender: NarraGender;
  traits: string[];
  appearance: string;
  /** Рукописная манера речи героя; без неё секция в карточке скрывается. */
  speechStyle?: string;
  speechExamples?: string[];
  /** Доля книги (0…0.95), с которой герой открывается; по умолчанию 0. */
  unlockProgress?: number;
  /** Глава первого значимого появления — для заглушки запертого героя. */
  appearanceChapter?: number;
};

function characters(
  definitions: CharacterDefinition[],
  voiceOptions: AssignVoicesOptions = {},
): NarraCharacter[] {
  // Порядок определений — уже посчитанный rank по убыванию значимости.
  const plan = assignVoices(
    definitions.map((definition, index) => ({
      id: definition.id,
      gender: definition.gender,
      rank: definitions.length - index,
    })),
    voiceOptions,
  );
  return definitions.map((definition) => ({
    id: definition.id,
    name: definition.name,
    fullName: definition.fullName,
    role: definition.role,
    gender: definition.gender,
    voice: plan.assignments[definition.id]?.voice ?? plan.narratorVoice,
    voiceProsody: plan.assignments[definition.id]?.prosody,
    traits: definition.traits,
    // Если рукописной манеры речи нет — пустая строка честнее шаблонной
    // заглушки; секция «Манера речи» в карточке скрывается сама.
    speechStyle: definition.speechStyle ?? "",
    speechExamples: definition.speechExamples ?? [],
    appearancePrompt: definition.appearance,
    unlockProgress: definition.unlockProgress ?? 0,
    ...(definition.appearanceChapter ? { appearanceChapter: definition.appearanceChapter } : {}),
    // Приветствие не шаблонное: первое сообщение генерирует чат в характере героя
  }));
}

